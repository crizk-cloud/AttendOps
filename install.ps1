<#
AttendOps installer for Windows (PowerShell 5.1+). Safe to run again: it keeps an existing .env and data.

  powershell -ExecutionPolicy Bypass -File .\install.ps1
  powershell -ExecutionPolicy Bypass -File .\install.ps1 -AdminEmail you@example.com -Port 8080 -Lan

-Lan lets other computers on the network open the app (Windows Firewall may ask for permission).
-Reset DELETES all AttendOps data and starts over (asks for confirmation).
Or just double-click install.cmd.
#>
param(
    [int]$Port = 8080,
    [switch]$Lan,
    [switch]$Reset,
    [string]$AdminEmail = ""
)
# Not "Stop": in Windows PowerShell 5.1 that turns any stderr output of docker into a fatal error.
# Native commands are checked through $LASTEXITCODE instead.
$ErrorActionPreference = "Continue"
Set-Location -LiteralPath $PSScriptRoot

function Say($msg) { Write-Host ""; Write-Host $msg -ForegroundColor Cyan }
function Die($msg) { Write-Host ""; Write-Host "ERROR: $msg" -ForegroundColor Red; exit 1 }

# Runs a native command and stops if it fails ($ErrorActionPreference does not cover exe exit codes).
function Run([string]$exe, [string[]]$argList) {
    & $exe @argList
    if ($LASTEXITCODE -ne 0) { Die "'$exe $($argList -join ' ')' failed (exit code $LASTEXITCODE)." }
}

function RandomToken([int]$bytes) {
    $buf = New-Object byte[] $bytes
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    $rng.GetBytes($buf)
    $rng.Dispose()
    return [Convert]::ToBase64String($buf).Replace('+', '-').Replace('/', '_')
}

Say "1/5 Checking Docker"
if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
    Die "Docker is not installed. Install Docker Desktop from https://www.docker.com/products/docker-desktop/ , start it, then run this again."
}
& docker compose version *> $null
if ($LASTEXITCODE -ne 0) { Die "'docker compose' is not available. Please update Docker Desktop." }
& docker info *> $null
if ($LASTEXITCODE -ne 0) { Die "Docker Desktop is installed but not running. Start it, wait until it shows 'Engine running', then run this again." }

if ($Reset) {
    Say "RESET: this deletes ALL AttendOps data (imported logs, devices, accounts) on this computer."
    $confirm = Read-Host "Type DELETE to continue"
    if ($confirm -cne "DELETE") { Die "Reset cancelled." }
    $ids = & docker ps -aq --filter label=com.docker.compose.project=attendops
    if ($ids) { & docker rm -f @($ids) *> $null }
    & docker volume rm attendops_pgdata *> $null
    $oldEnv = Join-Path $PSScriptRoot ".env"
    if (Test-Path -LiteralPath $oldEnv) { Rename-Item -LiteralPath $oldEnv -NewName (".env.old-" + (Get-Date -Format "yyyyMMddHHmmss")) }
    Write-Host "Old data removed (previous .env, if any, kept as .env.old-*)."
}

Say "2/5 Configuration (.env)"
$envPath = Join-Path $PSScriptRoot ".env"
if (Test-Path -LiteralPath $envPath) {
    Write-Host "Keeping existing .env (secrets and settings unchanged)."
    $existing = Get-Content -LiteralPath $envPath -Raw
    foreach ($key in "POSTGRES_PASSWORD", "JWT_SECRET", "DEVICE_CREDENTIALS_KEY") {
        if ($existing -notmatch "(?m)^$key=.+") { Die ".env exists but has no $key. Fix it or move the file away." }
    }
} else {
    & docker volume inspect attendops_pgdata *> $null
    if ($LASTEXITCODE -eq 0) {
        Die ("Found existing AttendOps data (Docker volume attendops_pgdata) but no .env file.`n" +
             "New secrets would not match it. Restore your backed-up .env into this folder and run again.`n" +
             "To deliberately start over and DELETE all AttendOps data instead:  .\install.ps1 -Reset")
    }
    $bind = if ($Lan) { "0.0.0.0" } else { "127.0.0.1" }
    $lines = @(
        "# Generated by install.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm'). Keep this file private.",
        "# BACK IT UP: without DEVICE_CREDENTIALS_KEY the stored device passwords cannot be decrypted.",
        "POSTGRES_DB=attendops",
        "POSTGRES_USER=attendops",
        "POSTGRES_PASSWORD=$((RandomToken 24).TrimEnd('='))",
        "JWT_SECRET=$((RandomToken 48).TrimEnd('='))",
        "DEVICE_CREDENTIALS_KEY=$(RandomToken 32)",
        "APP_PORT=$Port",
        "APP_BIND=$bind",
        "APP_TIMEZONE=Asia/Beirut",
        "COOKIE_SECURE=false"
    )
    # UTF-8 without BOM and LF line endings, so docker compose reads the first key correctly.
    [System.IO.File]::WriteAllText($envPath, (($lines -join "`n") + "`n"), (New-Object System.Text.UTF8Encoding $false))
    Write-Host "Created .env with new random secrets."
}
$envText = Get-Content -LiteralPath $envPath -Raw
$Port = if ($envText -match "(?m)^APP_PORT=(\d+)") { [int]$Matches[1] } else { 8080 }
$bindNow = if ($envText -match "(?m)^APP_BIND=(\S+)") { $Matches[1] } else { "127.0.0.1" }

Say "3/5 Building and starting (the first run downloads images and can take several minutes)"
Run "docker" @("compose", "up", "-d", "--build")

Say "4/5 Waiting for the app to become ready"
$url = "http://127.0.0.1:$Port"
$ready = $false
for ($i = 0; $i -lt 90; $i++) {
    try {
        $r = Invoke-WebRequest -UseBasicParsing -TimeoutSec 5 -Uri "$url/api/health" -ErrorAction Stop
        if ($r.Content -match '"database":true') { $ready = $true; break }
    } catch { }
    Start-Sleep -Seconds 2
}
if (-not $ready) {
    & docker compose logs --tail 40 app
    Die "The app did not start. See the log above."
}
Write-Host "Ready."

Say "5/5 Admin account"
$admins = (& docker compose exec -T app python -m app.cli admin-count) -replace '\D', ''
if ([int]("0" + $admins) -gt 0) {
    Write-Host "An admin account already exists."
} else {
    if (-not $AdminEmail) { $AdminEmail = Read-Host "Email for the first admin account" }
    if ($env:ATTENDOPS_ADMIN_PASSWORD) {
        Run "docker" @("compose", "exec", "-T", "-e", "ATTENDOPS_ADMIN_PASSWORD", "app", "python", "-m", "app.cli", "create-admin", "--email", $AdminEmail)
    } else {
        Run "docker" @("compose", "exec", "app", "python", "-m", "app.cli", "create-admin", "--email", $AdminEmail)
    }
}

Say "AttendOps is running: $url"
if ($bindNow -eq "0.0.0.0") {
    Write-Host "Other computers on the network can use http://<this-computer's-IP>:$Port"
}
Write-Host @"

It starts automatically whenever Docker Desktop is running
(Docker Desktop > Settings > General > 'Start Docker Desktop when you sign in').
  Stop:    docker compose stop
  Start:   docker compose start
  Logs:    docker compose logs -f app
  Update:  replace this folder with the new version (keep .env!), then run install again

IMPORTANT: back up the .env file (it holds the key that decrypts device passwords).
"@
Start-Process $url
