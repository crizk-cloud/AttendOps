#!/usr/bin/env bash
# AttendOps installer for macOS / Linux. Safe to run again: it keeps an existing .env and data.
#
#   ./install.sh                         # interactive
#   ./install.sh --admin-email you@x.lb  # admin password from ATTENDOPS_ADMIN_PASSWORD or prompted
#   ./install.sh --port 8080 --lan       # --lan lets other computers on the network open the app
#   ./install.sh --reset                 # DELETE all AttendOps data and start over (asks for confirmation)
set -euo pipefail
cd "$(dirname "$0")"

PORT=8080
BIND=127.0.0.1
ADMIN_EMAIL=""
RESET=0
while [ $# -gt 0 ]; do
  case "$1" in
    --port) PORT="$2"; shift 2 ;;
    --lan) BIND=0.0.0.0; shift ;;
    --admin-email) ADMIN_EMAIL="$2"; shift 2 ;;
    --reset) RESET=1; shift ;;
    -h|--help) sed -n '2,8p' "$0"; exit 0 ;;
    *) echo "Unknown option: $1" >&2; exit 2 ;;
  esac
done

say() { printf '\n\033[1m%s\033[0m\n' "$*"; }
die() { printf '\nERROR: %s\n' "$*" >&2; exit 1; }

say "1/5 Checking Docker"
command -v docker >/dev/null || die "Docker is not installed. Install Docker Desktop (https://www.docker.com/products/docker-desktop/) and run this again."
docker compose version >/dev/null 2>&1 || die "'docker compose' is not available. Update Docker Desktop / install the compose plugin."
docker info >/dev/null 2>&1 || die "Docker is installed but not running. Start Docker Desktop, wait until it says 'running', then run this again."

if [ "$RESET" = 1 ]; then
  say "RESET: this deletes ALL AttendOps data (imported logs, devices, accounts) on this computer."
  read -r -p "Type DELETE to continue: " CONFIRM
  [ "$CONFIRM" = "DELETE" ] || die "Reset cancelled."
  IDS=$(docker ps -aq --filter label=com.docker.compose.project=attendops)
  [ -z "$IDS" ] || docker rm -f $IDS >/dev/null
  docker volume rm attendops_pgdata >/dev/null 2>&1 || true
  [ ! -f .env ] || mv .env ".env.old-$(date +%Y%m%d%H%M%S)"
  echo "Old data removed (previous .env, if any, kept as .env.old-*)."
fi

rand() { head -c "$1" /dev/urandom | base64 | tr -d '\n'; }

say "2/5 Configuration (.env)"
if [ -f .env ]; then
  echo "Keeping existing .env (secrets and settings unchanged)."
  grep -q '^POSTGRES_PASSWORD=.\+' .env && grep -q '^JWT_SECRET=.\+' .env && grep -q '^DEVICE_CREDENTIALS_KEY=.\+' .env \
    || die ".env exists but is missing POSTGRES_PASSWORD, JWT_SECRET or DEVICE_CREDENTIALS_KEY. Fix it or move it away."
else
  if docker volume inspect attendops_pgdata >/dev/null 2>&1; then
    die "Found existing AttendOps data (Docker volume attendops_pgdata) but no .env file.
New secrets would not match it. Restore your backed-up .env into this folder and run again.
To deliberately start over and DELETE all AttendOps data instead:  ./install.sh --reset"
  fi
  umask 077
  cat > .env <<ENV
# Generated by install.sh on $(date '+%Y-%m-%d %H:%M'). Keep this file private.
# BACK IT UP: without DEVICE_CREDENTIALS_KEY the stored device passwords cannot be decrypted.
POSTGRES_DB=attendops
POSTGRES_USER=attendops
POSTGRES_PASSWORD=$(rand 24 | tr '+/' '-_' | tr -d '=')
JWT_SECRET=$(rand 48 | tr '+/' '-_' | tr -d '=')
DEVICE_CREDENTIALS_KEY=$(rand 32 | tr '+/' '-_')
APP_PORT=$PORT
APP_BIND=$BIND
APP_TIMEZONE=Asia/Beirut
COOKIE_SECURE=false
ENV
  echo "Created .env with new random secrets."
fi
PORT=$(grep -E '^APP_PORT=' .env | cut -d= -f2 || true); PORT=${PORT:-8080}
BIND=$(grep -E '^APP_BIND=' .env | cut -d= -f2 || true); BIND=${BIND:-127.0.0.1}

say "3/5 Building and starting (first run downloads images; this can take several minutes)"
docker compose up -d --build

say "4/5 Waiting for the app to become ready"
URL="http://127.0.0.1:$PORT"
for i in $(seq 1 90); do
  if curl -fsS "$URL/api/health" 2>/dev/null | grep -q '"database":true'; then echo "Ready."; break; fi
  [ "$i" = 90 ] && { docker compose logs --tail 40 app; die "The app did not start. See the log above."; }
  sleep 2
done

say "5/5 Admin account"
ADMINS=$(docker compose exec -T app python -m app.cli admin-count | tr -dc '0-9')
if [ "${ADMINS:-0}" -gt 0 ]; then
  echo "An admin account already exists."
else
  [ -n "$ADMIN_EMAIL" ] || read -r -p "Email for the first admin account: " ADMIN_EMAIL
  if [ -n "${ATTENDOPS_ADMIN_PASSWORD:-}" ]; then
    docker compose exec -T -e ATTENDOPS_ADMIN_PASSWORD app python -m app.cli create-admin --email "$ADMIN_EMAIL"
  else
    docker compose exec app python -m app.cli create-admin --email "$ADMIN_EMAIL"
  fi
fi

say "AttendOps is running: $URL"
if [ "$BIND" = "0.0.0.0" ]; then
  echo "Other computers on the network can use http://<this-computer's-IP>:$PORT"
fi
cat <<MSG

It starts automatically whenever Docker is running.
  Stop:     docker compose stop
  Start:    docker compose start
  Logs:     docker compose logs -f app
  Update:   get the new version of this folder, then run ./install.sh again

IMPORTANT: back up the .env file (it holds the key that decrypts device passwords).
MSG
